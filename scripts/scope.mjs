// Rewrites a generated CSS file so every selector is scoped, for hosts that must not be repainted.
//   node scripts/scope.mjs --in packages/css/type.css --scope .studio-scope --out <path>
// Line-based on purpose: every line that ends in "{" and is not an at-rule is a selector line.

import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const arg = (n, d) => {
  const i = process.argv.indexOf(n);
  return i > -1 ? process.argv[i + 1] : d;
};
const input = arg("--in");
const scope = arg("--scope");
const out = arg("--out");
if (!input || !scope || !out) {
  console.error("usage: node scripts/scope.mjs --in <css> --scope <selector> --out <css>");
  process.exit(1);
}

const scoped = fs
  .readFileSync(input, "utf8")
  .split("\n")
  .map((line) => {
    const trimmed = line.trim();
    if (!trimmed.endsWith("{") || trimmed.startsWith("@") || trimmed.startsWith("/*")) return line;
    const indent = line.slice(0, line.length - line.trimStart().length);
    const selector = trimmed.slice(0, -1).trim();
    const parts = selector
      .split(",")
      .map((s) => s.trim())
      .filter(Boolean)
      .map((s) => (/^(:root|html)$/.test(s) ? scope : `${scope} ${s}`));
    return `${indent}${parts.join(", ")} {`;
  })
  .join("\n");

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `/* scoped to ${scope} — generated by messer-ui scripts/scope.mjs */\n${scoped}`);
console.log(`scoped → ${out} (${(scoped.length / 1024).toFixed(1)} KB)`);
